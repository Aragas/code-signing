<#
.SYNOPSIS
  Updates NuGet package archives (.nupkg) with their newly signed binaries.

.DESCRIPTION
  Processes the package mapping generated by Expand-SigningFiles.ps1. For each extracted entry,
  the original unsigned entry is replaced with the signed version while preserving original
  timestamps and compression level. All other entries within the package remain untouched.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$MapPath
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression

$entries = @(Get-Content -Path $MapPath -Raw | ConvertFrom-Json)
foreach ($group in ($entries | Where-Object { $_ } | Group-Object Package)) {
    $zip = [System.IO.Compression.ZipFile]::Open($group.Name, [System.IO.Compression.ZipArchiveMode]::Update)
    try {
        foreach ($item in $group.Group) {
            $old = $zip.GetEntry($item.Entry)
            if (-not $old) { throw "Target entry '$($item.Entry)' was not found in package '$($group.Name)'." }
            $lastWrite = $old.LastWriteTime
            $old.Delete()
            $new = [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $item.File, $item.Entry, [System.IO.Compression.CompressionLevel]::Optimal)
            $new.LastWriteTime = $lastWrite
            Write-Host "Successfully updated '$($item.Entry)' in $(Split-Path $group.Name -Leaf)."
        }
    } finally {
        $zip.Dispose()
    }
}
